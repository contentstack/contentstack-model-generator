#!/usr/bin/env python3
"""
HTML Test Report Generator for contentstack-model-generator.

Converts a .trx test-results file (and an optional Cobertura coverage.xml)
into a single self-contained HTML report: pass/fail summary, per-class test
breakdown with failure details, and a code coverage section.

Usage:
  python3 Scripts/generate_test_report.py <path-to-trx> [path-to-coverage.cobertura.xml]

Or run tests first to generate both inputs:
  dotnet test contentstack.model.generator.tests/contentstack.model.generator.tests.csproj \\
      --logger "trx;LogFileName=test-results.trx" \\
      --collect:"XPlat Code Coverage" \\
      --results-directory contentstack.model.generator.tests/TestResults

Uses only the Python standard library (xml.etree.ElementTree) - no extra
dependencies to install. The .trx/coverage files parsed here are always
locally generated by `dotnet test`, not untrusted input.
"""

import glob
import os
import sys
import xml.etree.ElementTree as ET
from datetime import datetime

TRX_NS = {'': 'http://microsoft.com/schemas/VisualStudio/TeamTest/2010'}


def escape_html(text):
    if text is None:
        return ""
    text = str(text)
    return (text
            .replace('&', '&amp;')
            .replace('<', '&lt;')
            .replace('>', '&gt;')
            .replace('"', '&quot;')
            .replace("'", '&#39;'))


class TestReportGenerator:
    def __init__(self, trx_file, coverage_file=None):
        self.trx_file = trx_file
        self.coverage_file = coverage_file
        self.results = {
            'total': 0,
            'passed': 0,
            'failed': 0,
            'skipped': 0,
            'tests': [],
        }
        self.coverage = None

    def parse_trx(self):
        tree = ET.parse(self.trx_file)
        root = tree.getroot()

        result_summary = root.find('.//ResultSummary', TRX_NS)
        counters = result_summary.find('Counters', TRX_NS) if result_summary is not None else None
        if counters is not None:
            self.results['total'] = int(counters.get('total', 0))
            self.results['passed'] = int(counters.get('passed', 0))
            self.results['failed'] = int(counters.get('failed', 0))
            self.results['skipped'] = int(counters.get('notExecuted', 0))

        unit_tests_by_id = {el.get('id'): el for el in root.findall('.//UnitTest', TRX_NS)}

        for test_result in root.findall('.//UnitTestResult', TRX_NS):
            test_name = test_result.get('testName', 'Unknown')
            outcome = test_result.get('outcome', 'Unknown')
            duration = test_result.get('duration', '0')

            try:
                hours, minutes, seconds = duration.split(':')
                total_seconds = int(hours) * 3600 + int(minutes) * 60 + float(seconds)
                duration_str = f"{total_seconds:.3f}s"
            except (ValueError, AttributeError):
                duration_str = duration

            error_message = None
            error_stacktrace = None
            output_elem = test_result.find('Output', TRX_NS)
            if output_elem is not None:
                error_info = output_elem.find('ErrorInfo', TRX_NS)
                if error_info is not None:
                    message_elem = error_info.find('Message', TRX_NS)
                    stacktrace_elem = error_info.find('StackTrace', TRX_NS)
                    if message_elem is not None:
                        error_message = message_elem.text
                    if stacktrace_elem is not None:
                        error_stacktrace = stacktrace_elem.text

            test_def = unit_tests_by_id.get(test_result.get('testId', ''))
            category = 'General'
            if test_def is not None:
                test_method = test_def.find('.//TestMethod', TRX_NS)
                if test_method is not None:
                    class_name = test_method.get('className', '')
                    if class_name:
                        category = class_name.split('.')[-1]

            self.results['tests'].append({
                'name': test_name,
                'outcome': outcome,
                'duration': duration_str,
                'category': category,
                'error_message': error_message,
                'error_stacktrace': error_stacktrace,
            })

        return True

    def parse_coverage(self):
        if not self.coverage_file or not os.path.exists(self.coverage_file):
            return

        tree = ET.parse(self.coverage_file)
        root = tree.getroot()

        # ModelGenerator.cs (and any other file) is split across multiple
        # <class> entries by coverlet (the class itself plus one per
        # compiler-generated async state machine) - aggregate by filename
        # so each source file shows as a single row.
        files = {}
        for cls in root.iter('class'):
            filename = cls.get('filename', cls.get('name', 'unknown'))
            lines_el = cls.find('lines')
            if lines_el is None:
                continue
            entry = files.setdefault(filename, {'valid': 0, 'covered': 0})
            for line in lines_el.findall('line'):
                entry['valid'] += 1
                if int(line.get('hits', 0)) > 0:
                    entry['covered'] += 1

        classes = []
        total_valid = 0
        total_covered = 0
        for filename, stats in files.items():
            valid = stats['valid']
            covered = stats['covered']
            total_valid += valid
            total_covered += covered
            classes.append({
                'filename': filename,
                'lines_valid': valid,
                'lines_covered': covered,
                'line_rate': (covered / valid * 100) if valid else 0.0,
            })

        classes.sort(key=lambda c: c['line_rate'])

        self.coverage = {
            'line_rate': float(root.get('line-rate', 0)) * 100,
            'branch_rate': float(root.get('branch-rate', 0)) * 100,
            'lines_valid': total_valid,
            'lines_covered': total_covered,
            'classes': classes,
        }

    def generate_coverage_section_html(self):
        if not self.coverage:
            return ""

        cov = self.coverage
        rows_html = ""
        for c in cov['classes']:
            rate = c['line_rate']
            bar_class = 'good' if rate >= 80 else 'warn' if rate >= 50 else 'bad'
            rows_html += f"""
                        <tr>
                            <td class="coverage-filename">{escape_html(c['filename'])}</td>
                            <td>
                                <div class="coverage-bar-track">
                                    <div class="coverage-bar-fill {bar_class}" style="width: {rate}%"></div>
                                </div>
                            </td>
                            <td class="coverage-pct">{rate:.1f}%</td>
                            <td class="coverage-counts">{c['lines_covered']} / {c['lines_valid']}</td>
                        </tr>
"""

        return f"""
        <div class="coverage-section">
            <h2 style="margin-bottom: 30px; font-size: 2em;">Code Coverage</h2>
            <div class="summary">
                <div class="summary-card">
                    <div class="number total">{cov['line_rate']:.1f}%</div>
                    <div class="label">Line Coverage</div>
                </div>
                <div class="summary-card">
                    <div class="number total">{cov['branch_rate']:.1f}%</div>
                    <div class="label">Branch Coverage</div>
                </div>
                <div class="summary-card">
                    <div class="number passed">{cov['lines_covered']}</div>
                    <div class="label">Lines Covered</div>
                </div>
                <div class="summary-card">
                    <div class="number">{cov['lines_valid']}</div>
                    <div class="label">Total Lines</div>
                </div>
            </div>
            <table class="test-table coverage-table">
                <thead>
                    <tr>
                        <th style="width: 40%">File</th>
                        <th style="width: 30%">Line Coverage</th>
                        <th style="width: 10%">%</th>
                        <th style="width: 20%">Lines</th>
                    </tr>
                </thead>
                <tbody>
{rows_html}
                </tbody>
            </table>
        </div>
"""

