def find_first(pattern):
    matches = glob.glob(pattern, recursive=True)
    return matches[0] if matches else None


def main():
    print("=" * 80)
    print("contentstack-model-generator Test Report Generator")
    print("=" * 80)

    trx_file = sys.argv[1] if len(sys.argv) > 1 else find_first('contentstack.model.generator.tests/TestResults/**/*.trx')
    coverage_file = sys.argv[2] if len(sys.argv) > 2 else find_first('contentstack.model.generator.tests/TestResults/**/coverage.cobertura.xml')

    if not trx_file or not os.path.exists(trx_file):
        print("\nError: No .trx file found!")
        print(__doc__)
        sys.exit(1)

    print(f"\nTRX file: {trx_file}")
    print(f"Coverage file: {coverage_file or '(none found - report will omit coverage section)'}")

    generator = TestReportGenerator(trx_file, coverage_file)

    print("\nParsing test results...")
    generator.parse_trx()
    print(f"Found {generator.results['total']} tests "
          f"({generator.results['passed']} passed, {generator.results['failed']} failed, "
          f"{generator.results['skipped']} skipped)")

    if coverage_file:
        print("\nParsing coverage data...")
        generator.parse_coverage()
        if generator.coverage:
            print(f"Line coverage: {generator.coverage['line_rate']:.1f}% "
                  f"({generator.coverage['lines_covered']}/{generator.coverage['lines_valid']} lines)")

    timestamp = datetime.now().strftime('%Y%m%d_%H%M%S')
    output_file = generator.generate_html(f'test-report_{timestamp}.html')

    print("\n" + "=" * 80)
    print(f"Done. Open: file://{os.path.abspath(output_file)}")
    print("=" * 80)


if __name__ == "__main__":
    main()
